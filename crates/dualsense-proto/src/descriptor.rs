#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn descriptor_has_expected_size_and_collections() {
        assert_eq!(REPORT_DESCRIPTOR.len(), 437);
        assert_eq!(&REPORT_DESCRIPTOR[..6], &[0x05, 0x01, 0x09, 0x05, 0xA1, 0x01]);
        assert_eq!(REPORT_DESCRIPTOR[436], 0xC0); // END_COLLECTION
        // One input (0x01), one output (0x02), and every feature id the descriptor declares.
        for id in [0x01u8, 0x02, 0x05, 0x08, 0x09, 0x0A, 0x20, 0x21, 0x22] {
            assert!(
                REPORT_DESCRIPTOR.windows(2).any(|w| w == [0x85, id]),
                "report id {id:#04x} missing"
            );
        }
    }
}
